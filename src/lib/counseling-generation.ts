/** User-approved Page 1 directions, stored as corrections rather than invented AI measurements. */
export const counselingDesignDirections:Record<'A'|'B'|'C'|'D'|'E',Partial<PlanningParameters>>={
 A:{bangLength:'brow',bangWidth:'standard',bangDensity:'standard',bangPart:'none',bangFlow:'inward'},
 B:{bangLength:'below_brow',bangWidth:'narrow',bangDensity:'thin',bangPart:'none',bangFlow:'straight'},
 C:{bangLength:'cheekbone',bangWidth:'standard',bangDensity:'thin',bangPart:'center',bangFlow:'outward'},
 D:{bangLength:'long',bangWidth:'narrow',bangDensity:'thin',bangPart:'left',bangFlow:'side',sideBangLength:'cheekbone',faceFrameStart:'cheekbone',faceFrameLength:'chin',faceFrameDirection:'inward',faceFrameVolumePosition:'cheekbone'},
 E:{bangLength:'above_brow',bangWidth:'wide',bangDensity:'thick',bangPart:'none',bangFlow:'straight'}
};
export function prepareCounselingGeneration(j:Journey,options:{requireCombined?:boolean;legacyFixedDirections?:boolean}={}):Journey{
 let next=withDiagnosisSession(j);const s=next.diagnosisSession!,combined=options.requireCombined!==false;
 if(!next.photos.some(p=>p.view==='front'))throw new Error('CURRENTに本人の正面写真を追加してください。');
 if(combined&&s.simulationMode!=='STYLE_COLOR')throw new Error('STYLE設定で「髪型＋カラー」を選択してください。');
 if(s.simulationMode!=='STYLE_ONLY'&&!commonCounselingColor(next))throw new Error('COLOR写真の色味を確定してください。');
 if(s.simulationMode==='COLOR_ONLY')return next;
 if(combined&&!s.styleTarget.referenceImage)throw new Error('STYLE写真を追加してください。');
 let run=activePlanningRun(s);if(!run){next=planBangFaceFrameDesigns(next);run=activePlanningRun(next.diagnosisSession!);}
 if(!run||run.proposals.length!==5)throw new Error('本人の髪と顔を分析して、前髪5案を設計してください。');
 // New Page1 runs use measured, personalized proposals and explicit stylist edits.
 // Retain the former preset only for explicit legacy callers, never as AI judgment.
 if(!options.legacyFixedDirections)return next;
 if(counselingState(next).generationDesignRequests?.runId===run.id)return next;
 const selectedId=selectedPlannedDesign(next.diagnosisSession!)?.design.id;
 for(const d of run.proposals){next=setPlannedDesignDraft(next,d.id,{...d.parameters,...counselingDesignDirections[d.label]});next=confirmPlannedDesignCorrection(next,d.id,'Page 1：承認済みA〜Eデザイン指定');}
 if(selectedId)next=selectPlannedDesign(next,selectedId,'Page 1：選択した案の生成条件を確定');
 return editCounseling(next,{generationDesignRequests:{runId:run.id,version:'page1-design-directions-v1',createdAt:new Date().toISOString()}});
}
/** Existing STYLE-only / COLOR-only journeys remain available inside the details panel. */
export const prepareCounselingSimulation=(j:Journey)=>prepareCounselingGeneration(j,{requireCombined:false});
export function counselingGenerationJob(j:Journey,label:'MAIN'|'A'|'B'|'C'|'D'|'E'){
 const s=j.diagnosisSession;if(!s)return null;const b=activeSimulationBatch(s);return s.hairSimulation?.jobs.find(x=>x.batchId===b?.id&&x.label===label)??null;
}
export function counselingGeneratedDesign(j:Journey,label:'MAIN'|'A'|'B'|'C'|'D'|'E'){
 const job=counselingGenerationJob(j,label);if(!job||simulationJobStatus(j.diagnosisSession!,job)!=='COMPLETE')return null;
 const image=completedJobAsset(j.diagnosisSession!,job.id);return image?.origin==='REAL_API'?image:null;
}
export function counselingPreferredDesignLabels(j:Journey):('A'|'B'|'C'|'D'|'E')[]{
 const selected=j.diagnosisSession?selectedPlannedDesign(j.diagnosisSession):null;return selected?[selected.design.label]:['A','B','C','D','E'];
}
function currentFinalAsset(j:Journey){
 const s=j.diagnosisSession;if(!s)return null;const selected=selectedPlannedDesign(s),asset=selectedSimulationAsset(s);
 if(s.simulationMode!=='COLOR_ONLY'&&selected){const job=counselingGenerationJob(j,selected.design.label);return job?.designId===selected.design.id?counselingGeneratedDesign(j,selected.design.label):null;}
 return asset?.origin==='REAL_API'?asset:counselingGeneratedDesign(j,'MAIN');
}
/** Final display never re-colors generated bytes or promotes a local/reference preview.
 * Legacy protection spliced two silhouettes and re-applied an absolute Lab target;
 * keep its history, but require regeneration instead of displaying that composite.
 */
export function counselingFinalDesign(j:Journey){
 const asset=currentFinalAsset(j);if(!asset)return null;
 const event=j.diagnosisSession?.hairSimulation?.events.find(e=>e.id===asset.eventId);
 if(event?.metadata?.postprocessing?.version==='hair-only-protection-v1')return null;
 if((event?.metadata?.comparisonCrop||event?.metadata?.requiresStylistReview)&&j.diagnosisSession?.hairSimulation?.reviews.findLast(r=>r.generationId===asset.eventId)?.decision!=='ACCEPTED')return null;
 return asset;
}
export function counselingFinalDisplay(j:Journey){
 const asset=counselingFinalDesign(j);
 if(asset)return {status:'REAL_API' as const,dataUrl:asset.dataUrl,assetId:asset.id};
 return {status:j.photos.some(p=>p.view==='front')?'NOT_GENERATED' as const:'MOCK' as const,dataUrl:null,assetId:null};
}
/** A selection made in any retained detail editor must select the same generated child. */
export function alignCounselingSelection(j:Journey):Journey{
 const s=j.diagnosisSession,planned=s?selectedPlannedDesign(s):null;if(!s||s.simulationMode==='COLOR_ONLY'||!planned)return j;
 const job=counselingGenerationJob(j,planned.design.label),asset=counselingGeneratedDesign(j,planned.design.label);
 if(!job||!asset||job.designId!==planned.design.id||selectedSimulationAsset(s)?.id===asset.id)return j;
 return selectSimulationDesign(j,job.id);
}
